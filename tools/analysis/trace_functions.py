"""Derive call/store-traced copies of selected generated functions for lockstep shadow validation.

Retail port of the demo decomp's tools/trace_functions.py
(supermanReturns-demo-decomp); the transformation is unchanged.

Why: hand rewrites of routines whose callees have side effects (virtual calls
that draw, update or erase list elements) cannot be validated by running the
original and the rewrite on the same input: the callees would run twice. The
lockstep shadow (port/src/native_renderer/lockstep_shadow.h) instead runs the
original once, as a traced copy, and the rewrite in step with it on a fiber
against a copy-on-write view of guest memory. At every call the original makes,
the rewrite must make the same call (target, return address, argument
registers) and both must have written the same bytes since the previous call.

For each selected function this tool copies the ReXGlue body from
port/generated/default verbatim, except:
  * every call `sub_X(ctx, base);` / `REX_CALL_INDIRECT_FUNC(t);` is wrapped in
    T_BEFORE(ctx, target) / T_AFTER(ctx);
  * `__savegprlr_N` logs the register save area it is about to write;
    `__restgprlr_N` (no stores) is left alone;
  * REX_STORE_U8/16/32/64 become T_STORE_U*, which log the old bytes first;
  * aligned vector stores (stvx: simde_mm_store_si128 to REX_RAW_ADDR(ea))
    log their 16 bytes first.
memset (dcbz) and memcpy are refused.

Output: port/generated/traced/traced_<addr>.inc, functions Traced_<addr>.
Derived from the generated translation of the game: git-ignored, never committed.

Usage: python tools/analysis/trace_functions.py
"""
from __future__ import annotations

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / "port" / "generated" / "default"
OUT = ROOT / "port" / "generated" / "traced"

# Functions with a lockstep-validated rewrite (native_layer_walk.cpp).
FUNCTIONS = ["82783948"]

CALL = re.compile(r"^(\s*)(sub_([0-9A-F]{8})\(ctx, base\);|REX_CALL_INDIRECT_FUNC\(([^;]*)\);)\s*$")
SAVE = re.compile(r"^(\s*)__savegprlr_(\d+)\(ctx, base\);\s*$")
REST = re.compile(r"^\s*__restgprlr_\d+\(ctx, base\);\s*$")
VSTORE = re.compile(r"^(\s*)simde_mm_store_si128\(\(simde__m128i\*\)REX_RAW_ADDR\((\w+)\), ")
STORE = re.compile(r"\bREX_STORE_U(8|16|32|64)\(")


class Refused(Exception):
    pass


def function_body(name: str) -> str:
    pattern = re.compile(r"^DEFINE_REX_FUNC\(sub_%s\) \{\n(.*?)^\}\n" % name, re.S | re.M)
    for path in sorted(GENERATED.glob("superman_returns_recomp.*.cpp")):
        match = pattern.search(path.read_text(encoding="utf-8", errors="strict"))
        if match:
            return match.group(1)
    raise Refused(f"sub_{name} not found in {GENERATED}")


def trace(name: str, body: str) -> str:
    out = []
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("//") or not stripped:
            out.append(line)
            continue
        m = VSTORE.match(line)
        if m:
            out.append(f"{m.group(1)}T_SAVE_REGION({m.group(2)}, 16);")
            out.append(line)
            continue
        if "simde_mm_store_si128((simde__m128i*)REX_RAW_ADDR(" in line or "memset(" in line or "memcpy(" in line:
            raise Refused(f"sub_{name}: unsupported store form: {stripped}")
        m = SAVE.match(line)
        if m:
            n = int(m.group(2))
            size = 8 * (33 - n)
            out.append(f"{m.group(1)}T_SAVE_REGION(ctx.r1.u32 - {size}, {size - 4});")
            out.append(line)
            continue
        if REST.match(line):
            out.append(line)
            continue
        m = CALL.match(line)
        if m:
            target = f"0x{m.group(3)}u" if m.group(3) else f"(uint32_t)({m.group(4)})"
            out.append(f"{m.group(1)}T_BEFORE(ctx, {target});")
            out.append(line)
            out.append(f"{m.group(1)}T_AFTER(ctx);")
            continue
        if re.search(r"\b(sub_[0-9A-F]{8}|__\w+)\(ctx, base\)|REX_CALL", line):
            raise Refused(f"sub_{name}: unsupported call form: {stripped}")
        out.append(STORE.sub(lambda s: f"T_STORE_U{s.group(1)}(", line))
    return (f"static void Traced_{name}(PPCContext& __restrict ctx, uint8_t* base) {{\n"
            + "\n".join(out) + "\n}\n")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    header = ("// Generated by tools/analysis/trace_functions.py from port/generated/default.\n"
              "// Derived from the ReXGlue translation: do not commit, do not count as matching source.\n")
    ok = True
    for name in FUNCTIONS:
        try:
            text = trace(name, function_body(name))
        except Refused as error:
            print(f"[trace] refused: {error}", file=sys.stderr)
            ok = False
            continue
        (OUT / f"traced_{name}.inc").write_text(header + text, encoding="utf-8")
        print(f"[trace] sub_{name}: {text.count('T_BEFORE(')} calls, {text.count('T_STORE_U')} stores")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
