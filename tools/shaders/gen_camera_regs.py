"""Generates port/src/native_renderer/camera_regs.inc from the shader catalog:
for every vertex shader that declares the game's camera view-projection
(gViewProjectionXform, 4 rows), the VS float-constant register of its first
row. The rows are used as clip = (dot(row0, p), dot(row1, p), dot(row2, p),
dot(row3, p)) for a world position p (the city's instanced shader
2C45BFFE76D77398: oPos.x = dot(gViewProjectionXform(0), r1), ...).

The native renderer reads the frame's camera from them for DLSS (jitter,
motion vectors from depth).
usage: python tools/shaders/gen_camera_regs.py"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from srpaths import ARTIFACTS, NATIVE_SRC  # noqa: E402

CAMERA_NAME = 'gViewProjectionXform'


def camera_rows(catalog):
    """[(vertex shader hash, register)] sorted by hash."""
    rows = []
    for e in catalog:
        if e['type'] != 'vs':
            continue
        for k in e['reflection'].get('constants', []):
            if k['name'] == CAMERA_NAME and k.get('rows', 4) == 4 and k.get('cols', 4) == 4:
                rows.append((int(e['container_hash'], 16), k['reg']))
                break
    return sorted(rows)


def render(rows):
    out = ['// Generated by tools/shaders/gen_camera_regs.py - do not edit.',
           f'// {{vertex shader hash, VS constant register of {CAMERA_NAME} (4 rows)}}']
    out += [f'{{0x{h:016X}ull, {reg}}},' for h, reg in rows]
    return '\n'.join(out) + '\n'


def main():
    catalog = json.load(open(ARTIFACTS / 'catalog.json'))['shaders']
    rows = camera_rows(catalog)
    path = os.path.join(NATIVE_SRC, 'camera_regs.inc')
    with open(path, 'w', newline='\n') as f:
        f.write(render(rows))
    print(f'{len(rows)} shaders -> {path}')


if __name__ == '__main__':
    main()
