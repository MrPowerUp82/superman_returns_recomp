export function detectLanguage() {
  const saved = (() => { try { return localStorage.getItem('sr-lang'); } catch { return null; } })();
  if (saved === 'pt' || saved === 'en') return saved;
  return (navigator.language || 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}
